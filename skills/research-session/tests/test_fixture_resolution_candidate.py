import hashlib, json, pathlib, sys
import pytest
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / 'scripts'))
import review_ledger as l

def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()
def setup(tmp_path):
    project=tmp_path/'project-991'; canonical=project/'01-资料'/'reviews'; canonical.mkdir(parents=True)
    fixture=project/'tests'/'test_a'/'fixture.review.json'; fixture.parent.mkdir(parents=True)
    fixture.write_text(json.dumps({'binding':{'review_id':'review','point':1},'report':{'decision':'通过'},'round':1}),encoding='utf8')
    source=project/'tests'/'test_runtime.py'; source.write_text("def test_generate_fixture(tmp_path):\n    receipt = tmp_path / 'fixture.review.json'\n    dump(receipt, {'binding': {'review_id': 'review', 'point': 1}})\n",encoding='utf8')
    home=tmp_path/'ledger'; scope={'project_id':l.project_identity(str(project)),'project_root':str(project),'canonical':str(canonical)}
    l.scan_and_register(str(project),scope['project_id'],str(canonical),str(home))
    row=next(x for x in l.read_entries(str(home)) if x['kind']=='receipt')
    return scope, home, fixture, source, row

def summary(scope,home):
    return l.summarize(l.read_entries(str(home)),scope['project_id'],'review',1,scope['canonical'])

def reviewed(home, row, source, source_sha=None):
    attestation = home.parent / 'attestation.json'
    document = {
        'schema': 'research-session/fixture-attestation/v1',
        'target': {k: row[k] for k in ('entry_id','project_id','project_root','review_id',
                                       'point','receipt','receipt_sha256')},
        'reviewer': 'independent-reviewer', 'operator': 'operator',
        'reviewed_at': '2026-11-17T12:00:00+08:00', 'decision': 'fixture',
        'basis': 'Reviewed source, complete generated bytes and run records.',
        'limitations': 'Fixture record authenticity is an external trust assumption.',
        'evidence': [{'path': str(source), 'sha256': source_sha or sha(source)}],
    }
    review_output = home.parent / 'review-output.txt'
    review_output.write_text('Independent fixture review output for synthetic test only.',encoding='utf8')
    document['review_record'] = {'path': str(review_output), 'sha256': sha(review_output)}
    attestation.write_text(json.dumps(document),encoding='utf8')
    return l.resolve_reviewed_fixture(str(home),row['entry_id'],str(attestation),sha(attestation))

def test_attested_fixture_resolution_is_append_only_and_rechecked(tmp_path):
    scope,home,fixture,source,row=setup(tmp_path)
    assert l.blocking_reason(summary(scope,home)) is not None
    before=(home/'ledger.jsonl').read_bytes()
    reviewed(home,row,source)
    assert (home/'ledger.jsonl').read_bytes().startswith(before)
    assert not summary(scope,home)['outside_receipts']
    l.scan_and_register(scope['project_root'],scope['project_id'],scope['canonical'],str(home))
    assert not summary(scope,home)['outside_receipts']
    fixture.write_text('changed',encoding='utf8')
    assert l.blocking_reason(summary(scope,home)) is not None

def test_reject_canonical_or_changed_source_and_preserve_ledger(tmp_path):
    scope,home,fixture,source,row=setup(tmp_path)
    before=(home/'ledger.jsonl').read_bytes()
    with pytest.raises(ValueError): reviewed(home,row,source,'0'*64)
    assert (home/'ledger.jsonl').read_bytes()==before
    fixture.unlink()
    with pytest.raises(ValueError): reviewed(home,row,source)
    assert (home/'ledger.jsonl').read_bytes()==before

def test_canonical_receipt_never_resolved(tmp_path):
    scope,home,fixture,source,row=setup(tmp_path)
    dest=pathlib.Path(scope['canonical'])/'true.review.json'; dest.write_bytes(fixture.read_bytes())
    l.scan_and_register(scope['project_root'],scope['project_id'],scope['canonical'],str(home))
    row=next(x for x in l.read_entries(str(home)) if x.get('receipt')==str(dest))
    with pytest.raises(ValueError): reviewed(home,row,source)

def test_source_change_revokes_resolution(tmp_path):
    scope,home,fixture,source,row=setup(tmp_path)
    reviewed(home,row,source)
    source.write_text('changed',encoding='utf8')
    assert l.blocking_reason(summary(scope,home)) is not None

def test_unrelated_source_cannot_authorize_excluding_legacy_receipt(tmp_path):
    scope,home,fixture,source,row=setup(tmp_path)
    # A legacy or damaged receipt may have the same minimal JSON shape as a fixture.
    source.write_text('unrelated file, never generated this receipt',encoding='utf8')
    before=(home/'ledger.jsonl').read_bytes()
    with pytest.raises(ValueError):
        l.resolve_false_receipt(str(home),row['entry_id'],str(source),sha(source),'arbitrary note')
    assert (home/'ledger.jsonl').read_bytes()==before
    assert l.blocking_reason(summary(scope,home)) is not None

def test_changed_receipt_correction_must_support_explicit_revocation(tmp_path):
    scope,home,fixture,source,row=setup(tmp_path)
    reviewed(home,row,source)
    fixture.write_text('changed',encoding='utf8')
    assert l.blocking_reason(summary(scope,home)) is not None
    # Preserve both events and restore blocking, rather than requiring old bytes.
    l.revoke_false_receipt_resolution(str(home),row['entry_id'],'reviewed changed file')
    assert l.blocking_reason(summary(scope,home)) is not None

def test_repeated_resolve_revoke_cycles_keep_history_and_block(tmp_path):
    scope,home,fixture,source,row=setup(tmp_path)
    reviewed(home,row,source)
    assert l.blocking_reason(summary(scope,home)) is None
    l.revoke_false_receipt_resolution(str(home),row['entry_id'],'first review')
    assert l.blocking_reason(summary(scope,home)) is not None
    reviewed(home,row,source)
    assert l.blocking_reason(summary(scope,home)) is None
    l.revoke_false_receipt_resolution(str(home),row['entry_id'],'second review')
    assert l.blocking_reason(summary(scope,home)) is not None

def test_unrelated_generator_with_same_name_does_not_prove_provenance(tmp_path):
    scope,home,fixture,source,row=setup(tmp_path)
    source.write_text("def test_other():\n    filename = 'fixture.review.json'\n    dump(other, {})\n",encoding='utf8')
    with pytest.raises(ValueError): l.resolve_false_receipt(str(home),row['entry_id'],str(source),sha(source),'unrelated generator')

def test_source_must_bind_the_complete_generated_receipt(tmp_path):
    scope,home,fixture,source,row=setup(tmp_path)
    # Source only writes binding; recorded receipt additionally contains report and round.
    # File hashes and a matching dump target do not establish generation provenance.
    with pytest.raises(ValueError):
        l.resolve_false_receipt(str(home),row['entry_id'],str(source),sha(source),'not byte-equivalent')
    assert l.blocking_reason(summary(scope,home)) is not None

def test_evidence_under_linked_parent_cannot_resolve_receipt(tmp_path):
    scope,home,fixture,source,row=setup(tmp_path)
    link = tmp_path / 'linked-tests'
    try:
        link.symlink_to(source.parent, target_is_directory=True)
    except OSError as exc:
        if sys.platform != 'win32':
            pytest.skip(f'directory symlink unavailable: {exc}')
        import subprocess
        result = subprocess.run(['cmd', '/c', 'mklink', '/J', str(link), str(source.parent)],
                                capture_output=True, check=False)
        if result.returncode:
            pytest.skip('directory junction unavailable')
    linked_source = link / source.name
    before = (home/'ledger.jsonl').read_bytes()
    with pytest.raises(ValueError):
        reviewed(home,row,linked_source)
    assert (home/'ledger.jsonl').read_bytes() == before
    assert l.blocking_reason(summary(scope,home)) is not None

def test_receipt_under_linked_parent_cannot_be_resolved(tmp_path):
    scope,home,fixture,source,row=setup(tmp_path)
    parent = fixture.parent
    real_parent = parent.with_name('real-fixture-directory')
    parent.rename(real_parent)
    try:
        parent.symlink_to(real_parent, target_is_directory=True)
    except OSError as exc:
        if sys.platform != 'win32':
            pytest.skip(f'directory symlink unavailable: {exc}')
        import subprocess
        result = subprocess.run(['cmd', '/c', 'mklink', '/J', str(parent), str(real_parent)],
                                capture_output=True, check=False)
        if result.returncode:
            pytest.skip('directory junction unavailable')
    before = (home/'ledger.jsonl').read_bytes()
    with pytest.raises(ValueError):
        reviewed(home,row,source)
    assert (home/'ledger.jsonl').read_bytes() == before

def test_hardlinked_evidence_cannot_resolve_receipt(tmp_path):
    scope,home,fixture,source,row=setup(tmp_path)
