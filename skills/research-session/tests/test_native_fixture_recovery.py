"""Native consumer fixtures require runtime provenance, never a directory exemption."""
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import sys

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import review_ledger as ledger


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value), encoding="utf-8")
    return {"path": str(path.absolute()), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}


def native_case(tmp_path):
    project = tmp_path / "project-991"
    canonical = project / "01-资料/reviews"
    canonical.mkdir(parents=True)
    pack = write(project / "tests/native/pack.md", {"synthetic": True})
    fixture = project / "tests/native/result.review.json"
    receipt = {
        "schema": "research-session/review/v1", "intent_id": "fixture-intent",
        "guard_id": "fixture-guard", "round": 0, "report": None,
        "pack": {"path": pack["path"]},
        "binding": {"review_id": "review", "point": 1, "model": "fixture",
                    "pack_sha256": pack["sha256"], "route": {"wire_model": "fixture"}},
    }
    write(fixture, receipt)
    home = tmp_path / "ledger"
    scope = {"project_id": ledger.project_identity(str(project)), "project_root": str(project),
             "canonical": str(canonical)}
    ledger.scan_and_register(str(project), scope["project_id"], str(canonical), str(home))
    row = next(x for x in ledger.read_entries(str(home)) if x["kind"] == "receipt")
    source = write(tmp_path / "evidence/generator.py", {"synthetic_consumer": True})
    log = write(tmp_path / "evidence/run.log", {"passed": 1})
    run = write(tmp_path / "evidence/run.json", {
        "schema": "research-session/verification/v1", "exit_code": 0,
        "inputs": [{**source, "after_sha256": source["sha256"]}],
        "log": log["path"], "artifacts": [log],
    })
    artifacts = []
    for index, path in enumerate((fixture, Path(pack["path"]))):
        original = {"path": str(path), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
        preserved_path = tmp_path / "evidence/preserved" / str(index)
        preserved_path.parent.mkdir(parents=True, exist_ok=True)
        preserved_path.write_bytes(path.read_bytes())
        artifacts.append({"original": original, "preserved": {
            "path": str(preserved_path), "sha256": original["sha256"]}})
    provenance = write(tmp_path / "evidence/provenance.json", {
        "schema": "research-session/native-fixture-provenance/v1",
        "producer": source, "verification": run,
        "rows": [{"entry_id": row["entry_id"], "target": row, "artifacts": artifacts}],
    })
    review_record = write(tmp_path / "evidence/review.txt", {
        "source_and_runtime_reviewed": True, "limits": "Synthetic local reviewer trust only"})
    attestation = tmp_path / "attestation.json"
    doc = {
        "schema": "research-session/fixture-attestation/v1",
        "target": {key: row[key] for key in ("entry_id", "project_id", "project_root",
                                           "review_id", "point", "receipt", "receipt_sha256")},
        "decision": "fixture", "operator": "operator", "reviewer": "independent-reviewer",
        "reviewed_at": "2026-11-21T20:00:00+08:00",
        "basis": "Independently checked complete generated bytes, source and run record.",
        "limitations": "Trust remains with the operator and independent reviewer.",
        "review_record": review_record, "evidence": [provenance],
        "native_provenance": provenance,
    }
    write(attestation, doc)
    return scope, home, fixture, row, attestation, doc


def apply(home, row, attestation, dry_run=False):
    digest = hashlib.sha256(attestation.read_bytes()).hexdigest()
    return ledger.resolve_reviewed_fixture(str(home), row["entry_id"], str(attestation),
                                          digest, dry_run=dry_run)


def summary(scope, home):
    return ledger.summarize(ledger.read_entries(str(home)), scope["project_id"],
                            "review", 1, scope["canonical"])


def test_native_provenance_preview_apply_recheck_revoke_preserves_history(tmp_path):
    scope, home, fixture, row, attestation, doc = native_case(tmp_path)
    before = (home / "ledger.jsonl").read_bytes()
    apply(home, row, attestation, dry_run=True)
    assert (home / "ledger.jsonl").read_bytes() == before
    apply(home, row, attestation)
    assert (home / "ledger.jsonl").read_bytes().startswith(before)
    assert ledger.blocking_reason(summary(scope, home)) is None
    ledger.scan_and_register(scope["project_root"], scope["project_id"], scope["canonical"], str(home))
    assert ledger.blocking_reason(summary(scope, home)) is None
    assert ledger.read_entries(str(home))[0]["kind"] != "send_intent"
    ledger.revoke_false_receipt_resolution(str(home), row["entry_id"], "withdraw review")
    assert ledger.blocking_reason(summary(scope, home)) is not None


@pytest.mark.parametrize("change", ["no_proof", "wrong_row", "missing_source", "source_not_in_run",
                                   "changed_log", "changed_preserved", "different_bytes",
                                   "linked_source", "missing_original"])
def test_native_incomplete_or_drifted_provenance_never_excludes(tmp_path, change):
    scope, home, fixture, row, attestation, doc = native_case(tmp_path)
    manifest_path = Path(doc["native_provenance"]["path"])
    manifest = json.loads(manifest_path.read_bytes())
    if change == "no_proof":
        doc.pop("native_provenance")
    elif change == "wrong_row":
        manifest["rows"][0]["entry_id"] = "another-entry"
    elif change == "missing_source":
        Path(manifest["producer"]["path"]).unlink()
    elif change == "source_not_in_run":
        run_path = Path(manifest["verification"]["path"])
        run = json.loads(run_path.read_bytes())
        run["inputs"] = []
        manifest["verification"] = write(run_path, run)
    elif change == "changed_log":
        run = json.loads(Path(manifest["verification"]["path"]).read_bytes())
        Path(run["log"]).write_text("changed", encoding="utf-8")
    elif change == "changed_preserved":
        Path(manifest["rows"][0]["artifacts"][0]["preserved"]["path"]).write_text("changed")
    elif change == "different_bytes":
        artifact = manifest["rows"][0]["artifacts"][0]
        artifact["preserved"] = write(Path(artifact["preserved"]["path"]), {"not": "the receipt"})
    elif change == "linked_source":
        os.link(manifest["producer"]["path"], tmp_path / "extra-source-link")
    else:
        fixture.unlink()
    if "native_provenance" in doc:
        doc["native_provenance"] = write(manifest_path, manifest)
        doc["evidence"] = [doc["native_provenance"]]
    write(attestation, doc)
    before = (home / "ledger.jsonl").read_bytes()
    with pytest.raises(ValueError):
        apply(home, row, attestation)
    assert (home / "ledger.jsonl").read_bytes() == before


@pytest.mark.parametrize("kind", ["send_intent", "attempt", "lock"])
def test_native_fixture_cannot_hide_a_recorded_send(tmp_path, kind):
    scope, home, fixture, row, attestation, doc = native_case(tmp_path)
    ledger.append_entries(str(home), [ledger._base(kind, scope, "review", 1,
        intent_id="fixture-intent", guard_id="fixture-guard", pack_sha256=row["pack_sha256"])])
    with pytest.raises(ValueError):
        apply(home, row, attestation)


def test_new_send_evidence_invalidates_existing_native_correction(tmp_path):
    scope, home, fixture, row, attestation, doc = native_case(tmp_path)
    apply(home, row, attestation)
    ledger.append_entries(str(home), [ledger._base("send_intent", scope, "review", 1,
        intent_id="fixture-intent", pack_sha256=row["pack_sha256"])])
    assert summary(scope, home)["invalid_fixture_corrections"]


def test_concurrent_native_apply_is_one_append(tmp_path):
    scope, home, fixture, row, attestation, doc = native_case(tmp_path)
    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(lambda _: apply(home, row, attestation), range(2)))
    assert results[0]["entry_id"] == results[1]["entry_id"]
    assert sum(x.get("resolution_type") == "false_fixture" for x in ledger.read_entries(str(home))) == 1


def test_native_canonical_receipt_remains_ineligible(tmp_path):
    scope, home, fixture, row, attestation, doc = native_case(tmp_path)
    target = Path(scope["canonical"]) / "real.review.json"
    target.write_bytes(fixture.read_bytes())
    ledger.scan_and_register(scope["project_root"], scope["project_id"], scope["canonical"], str(home))
    real = next(x for x in ledger.read_entries(str(home)) if x.get("receipt") == str(target))
    doc["target"] = {key: real[key] for key in doc["target"]}
    write(attestation, doc)
    with pytest.raises(ValueError):
        apply(home, real, attestation)


@pytest.mark.parametrize("field,value", [
    ("route", {"wire_model": "fixture", "url": "https://provider.example/responses"}),
    ("model", "provider-model"),
])
def test_provider_shape_cannot_be_excluded_as_native_fixture(tmp_path, field, value):
    scope, home, fixture, row, attestation, doc = native_case(tmp_path)
    receipt = json.loads(fixture.read_bytes())
    receipt["binding"][field] = value
    write(fixture, receipt)
    ledger.scan_and_register(scope["project_root"], scope["project_id"], scope["canonical"], str(home))
    actual = next(x for x in reversed(ledger.read_entries(str(home)))
                  if x.get("receipt") == str(fixture))
    doc["target"] = {key: actual[key] for key in doc["target"]}
    manifest_path = Path(doc["native_provenance"]["path"])
    manifest = json.loads(manifest_path.read_bytes())
    manifest["rows"][0]["entry_id"] = actual["entry_id"]
    manifest["rows"][0]["target"] = actual
    artifact = manifest["rows"][0]["artifacts"][0]
    artifact["original"] = {"path": str(fixture), "sha256": hashlib.sha256(fixture.read_bytes()).hexdigest()}
    preserved = Path(artifact["preserved"]["path"])
    preserved.write_bytes(fixture.read_bytes())
    artifact["preserved"]["sha256"] = artifact["original"]["sha256"]
    doc["native_provenance"] = write(manifest_path, manifest)
    doc["evidence"] = [doc["native_provenance"]]
    write(attestation, doc)
    with pytest.raises(ValueError):
        apply(home, actual, attestation)


def test_changed_runtime_proof_restores_native_block(tmp_path):
    scope, home, fixture, row, attestation, doc = native_case(tmp_path)
    apply(home, row, attestation)
    manifest = json.loads(Path(doc["native_provenance"]["path"]).read_bytes())
    Path(manifest["verification"]["path"]).write_text("changed", encoding="utf-8")
    assert summary(scope, home)["invalid_fixture_corrections"]
