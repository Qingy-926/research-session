def test_two_processes_only_one_claims(tmp_path):
    import subprocess
    scope, home, fixture, evidence, row, attestation, doc = case(tmp_path)
    ledger.resolve_reviewed_fixture(str(home), row["entry_id"], str(attestation), digest(attestation))
    script = tmp_path / "claim.py"
    script.write_text(
        "import json,sys,time\n"
        "sys.path.insert(0,sys.argv[1])\nimport review_ledger as l\n"
        "from pathlib import Path\n"
        "scope=json.loads(Path(sys.argv[2]).read_text(encoding='utf8'))\n"
        "ready=Path(sys.argv[3]); release=Path(sys.argv[4]); ready.write_text('ready')\n"
        "deadline=time.monotonic()+10\n"
        "while not release.exists() and time.monotonic()<deadline: time.sleep(.01)\n"
        "result=l.claim_send(sys.argv[5],scope,{'review_id':'review','point':1,"
        "'pack_sha256':'abc'},sys.argv[6],1)\n"
        "print(json.dumps(result['claimed']))\n", encoding="utf8")
    scope_file = tmp_path / "scope.json"
    scope_file.write_text(json.dumps(scope), encoding="utf8")
    release = tmp_path / "release"
    processes = []
    for i in range(2):
        ready = tmp_path / f"ready-{i}"
        processes.append(subprocess.Popen(
            [sys.executable, "-B", str(script), str(pathlib.Path(ledger.__file__).parent),
             str(scope_file), str(ready), str(release), str(home), str(tmp_path / "pack.md")],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, encoding="utf8"))
    import time
    try:
        deadline = time.monotonic() + 10
        while not all((tmp_path / f"ready-{i}").exists() for i in range(2)):
            assert time.monotonic() < deadline
            time.sleep(.01)
        release.write_text("go", encoding="utf8")
        outputs = [p.communicate(timeout=15) for p in processes]
        assert all(p.returncode == 0 for p in processes), outputs
        assert sorted(json.loads(out) for out, _ in outputs) == [False, True]
    finally:
        for process in processes:
            if process.poll() is None:
                process.kill()
                process.wait()
