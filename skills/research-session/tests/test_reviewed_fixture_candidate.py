import hashlib
import json
import pathlib
import sys

import pytest

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "scripts"))
import review_ledger as ledger


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def case(tmp_path):
    project = tmp_path / "project-991"
    canonical = project / "01-资料" / "reviews"
    canonical.mkdir(parents=True)
    fixture = project / "tests" / "case" / "fixture.review.json"
    fixture.parent.mkdir(parents=True)
    fixture.write_text(json.dumps({"binding": {"review_id": "review", "point": 1},
                                   "round": 1, "report": {"decision": "通过"}}), encoding="utf8")
    evidence = project / "tests" / "run-record.txt"
    evidence.write_text("independently reviewed test source and run output", encoding="utf8")
    home = tmp_path / "ledger"
    scope = {"project_id": ledger.project_identity(str(project)), "project_root": str(project),
             "canonical": str(canonical)}
    ledger.scan_and_register(str(project), scope["project_id"], str(canonical), str(home))
    row = next(x for x in ledger.read_entries(str(home)) if x["kind"] == "receipt")
    attestation = tmp_path / "independent-review.json"
    document = {
        "schema": "research-session/fixture-attestation/v1",
        "target": {k: row[k] for k in ("entry_id", "project_id", "project_root",
                                       "review_id", "point", "receipt", "receipt_sha256")},
        "reviewer": "independent-reviewer",
        "operator": "correction-operator",
        "reviewed_at": "2026-11-17T12:00:00+08:00",
        "decision": "fixture",
        "basis": "Matched the complete generated bytes and the historical run evidence.",
        "limitations": "Recorded inputs do not prove tamper-free history.",
        "evidence": [{"path": str(evidence), "sha256": digest(evidence)}],
        "review_record": {"path": str(tmp_path / "review-output.txt"), "sha256": ""},
    }
    review_output = tmp_path / "review-output.txt"
    review_output.write_text("Independent review: fixture; checked test and run evidence; "
                             "historical authenticity remains a stated limit.", encoding="utf8")
    document["review_record"]["sha256"] = digest(review_output)
    attestation.write_text(json.dumps(document), encoding="utf8")
    return scope, home, fixture, evidence, row, attestation, document


def status(scope, home):
    entries = ledger.read_entries(str(home))
    return ledger.blocking_reason(ledger.summarize(
        entries, scope["project_id"], "review", 1, scope["canonical"]))


def test_reviewed_entry_is_append_only_and_evidence_change_restores_block(tmp_path):
    scope, home, fixture, evidence, row, attestation, _ = case(tmp_path)
    before = (home / "ledger.jsonl").read_bytes()
    ledger.resolve_reviewed_fixture(str(home), row["entry_id"], str(attestation), digest(attestation))
    assert (home / "ledger.jsonl").read_bytes().startswith(before)
    assert status(scope, home) is None
    evidence.write_text("changed", encoding="utf8")
    assert status(scope, home) is not None


@pytest.mark.parametrize("field,value", [
    ("entry_id", "different-entry"),
    ("project_id", "another/project"),
    ("project_root", "another-project"),
    ("review_id", "different-review"),
    ("point", 2),
    ("receipt", "different-receipt"),
    ("receipt_sha256", "0" * 64),
])
def test_attestation_must_bind_each_target_field(tmp_path, field, value):
    scope, home, fixture, evidence, row, attestation, doc = case(tmp_path)
    doc["target"][field] = value
    attestation.write_text(json.dumps(doc), encoding="utf8")
    before = (home / "ledger.jsonl").read_bytes()
    with pytest.raises(ValueError):
        ledger.resolve_reviewed_fixture(str(home), row["entry_id"], str(attestation), digest(attestation))
    assert (home / "ledger.jsonl").read_bytes() == before
    assert status(scope, home) is not None


def test_unreviewed_matching_source_never_authorizes_exclusion(tmp_path):
    scope, home, fixture, evidence, row, attestation, _ = case(tmp_path)
    source = tmp_path / "test_fake.py"
    source.write_text("def test_fake():\n    receipt = 'fixture.review.json'\n"
                      "    dump(receipt, {'binding': {'review_id': 'review', 'point': 1}})\n",
                      encoding="utf8")
    with pytest.raises(ValueError):
        ledger.resolve_false_receipt(str(home), row["entry_id"], str(source), digest(source), "fixture")
    assert status(scope, home) is not None


def test_receipt_in_authoritative_subdirectory_is_not_excluded(tmp_path):
    scope, home, fixture, evidence, row, attestation, doc = case(tmp_path)
    inside = pathlib.Path(scope["canonical"]) / "nested" / fixture.name
    inside.parent.mkdir()
    inside.write_bytes(fixture.read_bytes())
    ledger.scan_and_register(scope["project_root"], scope["project_id"], scope["canonical"], str(home))
    row = next(x for x in ledger.read_entries(str(home)) if x.get("receipt") == str(inside))
    doc["target"] = {k: row[k] for k in doc["target"]}
    attestation.write_text(json.dumps(doc), encoding="utf8")
    with pytest.raises(ValueError):
        ledger.resolve_reviewed_fixture(str(home), row["entry_id"], str(attestation), digest(attestation))


def test_duplicate_entry_id_blocks_correction(tmp_path):
    scope, home, fixture, evidence, row, attestation, doc = case(tmp_path)
    ledger_path = home / "ledger.jsonl"
    changed = dict(row)
    changed["receipt"] = str(tmp_path / "different-receipt.review.json")
    with ledger_path.open("a", encoding="utf8") as stream:
        stream.write(json.dumps(changed) + "\n")
    before = ledger_path.read_bytes()
    with pytest.raises(ValueError):
        ledger.resolve_reviewed_fixture(str(home), row["entry_id"], str(attestation), digest(attestation))
    assert ledger_path.read_bytes() == before


def test_rebinding_correction_to_another_attestation_blocks(tmp_path):
    scope, home, fixture, evidence, row, attestation, doc = case(tmp_path)
    ledger.resolve_reviewed_fixture(str(home), row["entry_id"], str(attestation), digest(attestation))
    assert status(scope, home) is None
    replacement = tmp_path / "replacement-review.json"
    doc["basis"] = "Different independent assessment"
    replacement.write_text(json.dumps(doc), encoding="utf8")
    path = home / "ledger.jsonl"
    lines = [json.loads(line) for line in path.read_text(encoding="utf8").splitlines()]
    correction = next(x for x in lines if x.get("resolution_type") == "false_fixture")
    correction["attestation"] = str(replacement)
    correction["attestation_sha256"] = digest(replacement)
    path.write_text("".join(json.dumps(x) + "\n" for x in lines), encoding="utf8")
    assert status(scope, home) is not None


def test_claim_finds_new_external_receipt_after_previous_scan(tmp_path):
    scope, home, fixture, evidence, row, attestation, doc = case(tmp_path)
    ledger.resolve_reviewed_fixture(str(home), row["entry_id"], str(attestation), digest(attestation))
