def test_two_concurrent_claims_only_one_wins(tmp_path):
    from concurrent.futures import ThreadPoolExecutor
    from threading import Barrier
    scope, home, fixture, evidence, row, attestation, doc = case(tmp_path)
    ledger.resolve_reviewed_fixture(str(home), row["entry_id"], str(attestation), digest(attestation))
    start = Barrier(2)
    def claim():
        start.wait()
        return ledger.claim_send(str(home), scope,
                                 {"review_id": "review", "point": 1, "pack_sha256": "abc"},
                                 str(tmp_path / "pack.md"), 1)["claimed"]
    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(lambda _: claim(), range(2)))
    assert sorted(results) == [False, True]


def test_original_client_still_blocks_corrected_fixture(tmp_path):
    import importlib.util
    source = pathlib.Path(__file__).parent / "fixtures" / "review_ledger_v218.py"
    assert digest(source) == "df29491b7e7ece09b021ddb681d8fc518bd6bbc0a526d1fc3da1d03388cef524"
    spec = importlib.util.spec_from_file_location("original_review_ledger", source)
    old = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(old)
    scope, home, fixture, evidence, row, attestation, doc = case(tmp_path)
    ledger.resolve_reviewed_fixture(str(home), row["entry_id"], str(attestation), digest(attestation))
    assert status(scope, home) is None
    old_summary = old.summarize(old.read_entries(str(home)), scope["project_id"],
                                "review", 1, scope["canonical"])
    assert old.blocking_reason(old_summary) is not None


